void assets_init(void) {
    // 1. Load Background Palettes (Palettes 0, 1, 2)
    for (int p = 0; p < 3; p++) {
        for (int c = 0; c < 16; c++) {
            BG_PALETTE_RAM[p * 16 + c] = s_bg_palettes[p][c];
        }
    }

    // 2. Load Sprite Palettes (Palettes 0, 1, 2, 3)
    for (int p = 0; p < 4; p++) {
        for (int c = 0; c < 16; c++) {
            OBJ_PALETTE_RAM[p * 16 + c] = s_obj_palettes[p][c];
        }
    }

    // 3. Load Background Tiles into CBB 0 (0x06000000)
    vu16* bg_tile_dst = (vu16*)(VRAM_BASE + (BG_CBB_TILES * 0x4000));
    const u16* bg_tile_src = (const u16*)s_bg_tiles;
    u32 bg_tile_words = sizeof(s_bg_tiles) / 2;
    for (u32 i = 0; i < bg_tile_words; i++) {
        bg_tile_dst[i] = bg_tile_src[i];
    }

    // 4. Load Sprite Tiles into OBJ VRAM (CBB 4 / 0x06010000)
    vu16* obj_tile_dst = (vu16*)(VRAM_BASE + 0x10000);
    const u16* obj_tile_src = (const u16*)s_sprite_tiles;
    u32 obj_tile_words = sizeof(s_sprite_tiles) / 2;
    for (u32 i = 0; i < obj_tile_words; i++) {
        obj_tile_dst[i] = obj_tile_src[i];
    }
}

void assets_load_stage_theme(u8 stage) {
    // Modify Palette 1 (Debris/Scaffolds) and Palette 2 (Nebula/Stars) depending on Stage
    if (stage == 1) {
        // Stage 1: Earth Orbit (Deep Blue Space & Azure Atmospheric Horizon)
        BG_PALETTE_RAM[2 * 16 + 1] = RGB15(1, 2, 6);   // Deep Blue
        BG_PALETTE_RAM[2 * 16 + 2] = RGB15(2, 4, 10);  // Azure Dust
        BG_PALETTE_RAM[2 * 16 + 3] = RGB15(4, 8, 16);  // Cyan Atmosphere
    } else if (stage == 2) {
        // Stage 2: Asteroid Infiltration (Crimson Gas Giant & Bronze Ore)
        BG_PALETTE_RAM[2 * 16 + 1] = RGB15(4, 1, 1);   // Crimson Void
        BG_PALETTE_RAM[2 * 16 + 2] = RGB15(8, 2, 2);   // Dark Amber Dust
        BG_PALETTE_RAM[2 * 16 + 3] = RGB15(14, 4, 3);  // Gas Giant Bands
    } else {
        // Stage 3: Void Core Fortress (Neon Violet Cyber Matrix)
        BG_PALETTE_RAM[2 * 16 + 1] = RGB15(2, 0, 4);   // Dark Violet
        BG_PALETTE_RAM[2 * 16 + 2] = RGB15(6, 1, 8);   // Purple Conduits
        BG_PALETTE_RAM[2 * 16 + 3] = RGB15(12, 2, 16); // Electric Magenta
    }
}
