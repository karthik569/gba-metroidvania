void assets_init(void) {
    load_bg_palette(s_bg_palette, 16);
    load_obj_palette(s_obj_palette, 16);

    // Populate OBJ palette banks 1..7 for brick-colored particles
    static const u16 s_particle_colors[8] = {
        RGB15(31, 31, 6),   // 0: Default yellow
        RGB15(31, 6, 6),    // 1: Red
        RGB15(10, 18, 31),  // 2: Blue
        RGB15(6, 31, 10),   // 3: Green
        RGB15(31, 28, 4),   // 4: Yellow
        RGB15(31, 8, 31),   // 5: Magenta
        RGB15(8, 31, 31),   // 6: Cyan
        RGB15(24, 25, 28)   // 7: Silver
    };
    for (u8 bank = 1; bank <= 7; bank++) {
        for (u8 c = 0; c < 16; c++) {
            OBJ_PALETTE_RAM[bank * 16 + c] = s_obj_palette[c];
        }
        OBJ_PALETTE_RAM[bank * 16 + 7] = s_particle_colors[bank];
    }

    // Load BG tiles into CharBlock 0
    load_bg_tiles(s_bg_tiles, sizeof(s_bg_tiles) / sizeof(u32), 0);

    // Load OBJ tiles into CharBlock 4
    load_obj_tiles(s_obj_tiles, sizeof(s_obj_tiles) / sizeof(u32));
}
