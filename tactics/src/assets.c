// =========================================================================
// Assets Initialization
// =========================================================================

void assets_init(void) {
    // 1. Load Background Palettes (Palettes 0, 1, 2)
    for (int p = 0; p < 3; p++) {
        for (int c = 0; c < 16; c++) {
            BG_PALETTE_RAM[p * 16 + c] = s_bg_palettes[p][c];
        }
    }

    // 2. Load Sprite Palettes (Palettes 0, 1, 2, 3)
    for (int p = 0; p < 4; p++) {
        for (int c = 0; c < 16; c++) {
            OBJ_PALETTE_RAM[p * 16 + c] = s_obj_palettes[p][c];
        }
    }

    // 3. Load Background Tiles into CBB 0 (0x06000000)
    vu16* bg_tile_dst = (vu16*)(VRAM_BASE + (BG_CBB_TILES * 0x4000));
    const u16* bg_tile_src = (const u16*)s_bg_tiles;
    u32 bg_tile_words = sizeof(s_bg_tiles) / 2;
    for (u32 i = 0; i < bg_tile_words; i++) {
        bg_tile_dst[i] = bg_tile_src[i];
    }

    // 4. Load Sprite Tiles into OBJ VRAM (CBB 4 / 0x06010000)
    vu16* obj_tile_dst = (vu16*)(VRAM_BASE + 0x10000);
    const u16* obj_tile_src = (const u16*)s_sprite_tiles;
    u32 obj_tile_words = sizeof(s_sprite_tiles) / 2;
    for (u32 i = 0; i < obj_tile_words; i++) {
        obj_tile_dst[i] = obj_tile_src[i];
    }
}
